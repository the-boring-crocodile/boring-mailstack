#!/usr/bin/env python3
"""resieve-watch: run resieve --apply for an account after its active Sieve
filter changed (DECISIONS.md, "Automatic resieve after a filter change").

Stalwart reports ManageSieve script changes by webhook (POST /), without
saying whose (the event carries no account). On an event, and every
CHECK_SECONDS as a fallback, the watcher waits until no change came in for
QUIET_SECONDS, then reads each enabled account's active script and runs
resieve --apply for every account whose script differs from the one it last
ran for. One run at a time.

First start: the current scripts are recorded without a run, so a deploy
does not move mail by itself.

State: /state/applied.json (account -> sha256 of the script last applied).
A version whose run failed is tried again at the next checks, at
most MAX_FAILURES times; then the watcher waits for the next filter change.
Accounts: /config/stalwart-accounts.json (generated by init); an account
with "resieve_enabled": false is left alone.

Re-sort chute: mail-provenance POSTs /resort with the mails a human moved
into INBOX (or Junk); they are re-sorted together once the moves have gone
quiet. Pending re-sorts are kept in /state/resort.json, so a restart does
not lose them.

By hand (tools/resieve runs this in the container):

    resieve-watch resieve ACCOUNT [--apply] [--limit N] [--mailbox PATH]
"""
import base64
import email.utils
import hashlib
import json
import os
import signal
import ssl
import subprocess
import sys
import tempfile
import threading
import time
import urllib.request
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

ACCOUNTS = Path("/config/stalwart-accounts.json")
STATE = Path("/state/applied.json")
MAX_FAILURES = 3
# The JMAP session, for the watcher and for resieve (compose sets it).
SESSION_URL = os.environ.get("RESIEVE_URL", "")
RESIEVE = "/usr/local/bin/mailstack-resieve"
QUIET_SECONDS = 60.0
CHECK_SECONDS = 3600.0
PORT = 8080
# Stalwart on the private Docker network: its own certificate (DECISIONS.md,
# TLS inside the stack).
CTX = ssl._create_unverified_context()

SUMMARY_KEYS = ("messages evaluated", "errors", "protected", "already correct",
                "would move", "applied moves", "mutation errors")


def say(text):
    print(f"resieve-watch: {text}", flush=True)


def load_accounts(enabled_only=True):
    accounts = json.loads(ACCOUNTS.read_text())
    return [a for a in accounts if a["resieve_enabled"] or not enabled_only]


def login(account):
    return account["login"]


def fetch(account, url, body=None):
    """GET (body None) or POST JSON as the account; the response bytes."""
    token = base64.b64encode(f'{login(account)}:{account["password"]}'.encode()).decode()
    request = urllib.request.Request(url, data=json.dumps(body).encode() if body is not None else None)
    request.add_header("Authorization", f"Basic {token}")
    if body is not None:
        request.add_header("Content-Type", "application/json")
    with urllib.request.urlopen(request, timeout=30, context=CTX) as response:
        return response.read()


def active_script(account):
    """sha256 of the account's active Sieve script, or None if it has none."""
    session = json.loads(fetch(account, SESSION_URL))
    account_id = session["primaryAccounts"]["urn:ietf:params:jmap:sieve"]
    using = ["urn:ietf:params:jmap:core", "urn:ietf:params:jmap:sieve"]
    result = json.loads(fetch(account, session["apiUrl"], {"using": using, "methodCalls": [
        ["SieveScript/query", {"accountId": account_id, "filter": {"isActive": True}}, "q"],
        ["SieveScript/get", {"accountId": account_id, "#ids": {
            "resultOf": "q", "name": "SieveScript/query", "path": "/ids"}, "properties": ["blobId"]}, "g"],
    ]}))
    scripts = result["methodResponses"][1][1]["list"]
    if not scripts:
        return None
    url = (session["downloadUrl"].replace("{accountId}", account_id)
           .replace("{blobId}", scripts[0]["blobId"]).replace("{name}", "script.sieve")
           .replace("{type}", "application%2Fsieve"))
    text = fetch(account, url)
    return hashlib.sha256(text).hexdigest()


def resieve_env(account, apply):
    """resieve's environment for an account: its login, provenance key and
    the folders it never takes mail out of (absent: resieve's default)."""
    env = {
        **os.environ,
        "RESIEVE_USERNAME": login(account),
        "RESIEVE_PASSWORD": account["password"],
        "RESIEVE_ACCOUNT": account["id"],
    }
    if apply:
        env["RESIEVE_APPLY"] = "1"
    if "resieve_protected_folders" in account:
        env["RESIEVE_PROTECTED_FOLDERS"] = ",".join(account["resieve_protected_folders"])
    return env


def run_resieve(account, resort_ids=None):
    env = resieve_env(account, apply=True)
    started = time.time()
    # The ids go in a file: a folder restructure can move more mails than
    # fit into one environment variable.
    with tempfile.NamedTemporaryFile("w", prefix="resort-", suffix=".ids") as ids_file:
        if resort_ids:
            ids_file.write("\n".join(sorted(resort_ids)) + "\n")
            ids_file.flush()
            env["RESIEVE_RESORT_IDS_FILE"] = ids_file.name
        done = subprocess.run([RESIEVE], env=env, capture_output=True, text=True)
    summary = {}
    for line in done.stdout.splitlines():
        key, _, value = line.partition(":")
        if key.strip() in SUMMARY_KEYS:
            summary[key.strip()] = value.strip()
    for line in done.stderr.splitlines()[-5:]:
        say(f"{account['id']}: {line}")
    what = f"re-sort of {len(resort_ids)} mail(s)" if resort_ids else "resieve --apply"
    say(f"{account['id']}: {what} exit {done.returncode} in {time.time() - started:.1f} s; "
        + ", ".join(f"{k} {v}" for k, v in summary.items()))
    return done.returncode == 0


NOTICE = """\
Your filter change could not be applied to the mail already in your mailbox.

New mail is sorted by the new filter as usual. Mail that was here before
stays where it was. To try again, save the filter once more (Settings ->
Filters); if this message comes back, tell the person who runs your mail
server.

-- mailstack (re-sorting after a filter change)
"""


def notify_gave_up(account):
    """Put a notice into the account's INBOX (JMAP import: local only, no
    filter, no spam check)."""
    session = json.loads(fetch(account, SESSION_URL))
    account_id = session["primaryAccounts"]["urn:ietf:params:jmap:mail"]
    using = ["urn:ietf:params:jmap:core", "urn:ietf:params:jmap:mail"]
    api = session["apiUrl"]
    boxes = json.loads(fetch(account, api, {"using": using, "methodCalls": [
        ["Mailbox/query", {"accountId": account_id, "filter": {"role": "inbox"}}, "q"]]}))
    inbox = boxes["methodResponses"][0][1]["ids"][0]
    address = account["address"]
    message = (f"From: mailstack <{address}>\r\nTo: <{address}>\r\n"
               f"Subject: Your filter change could not be applied to existing mail\r\n"
               f"Date: {email.utils.formatdate(localtime=True)}\r\n"
               f"Message-ID: {email.utils.make_msgid(domain='mailstack.invalid')}\r\n"
               f"Auto-Submitted: auto-generated\r\nContent-Type: text/plain; charset=utf-8\r\n\r\n"
               + NOTICE.replace("\n", "\r\n")).encode()
    token = base64.b64encode(f'{login(account)}:{account["password"]}'.encode()).decode()
    upload = urllib.request.Request(session["uploadUrl"].replace("{accountId}", account_id),
                                    data=message, headers={"Authorization": f"Basic {token}",
                                                           "Content-Type": "message/rfc822"})
    with urllib.request.urlopen(upload, timeout=30, context=CTX) as response:
        blob = json.loads(response.read())["blobId"]
    fetch(account, api, {"using": using, "methodCalls": [["Email/import", {
        "accountId": account_id,
        "emails": {"n": {"blobId": blob, "mailboxIds": {inbox: True}}}}, "i"]]})


class Watcher:
    def __init__(self, check=active_script, run=run_resieve, accounts=load_accounts,
                 state_path=STATE, clock=time.monotonic, notify=notify_gave_up):
        self.check, self.run, self.accounts = check, run, accounts
        self.state_path, self.clock, self.notify = state_path, clock, notify
        self.lock = threading.Lock()
        self.changed_at = None          # time of the last event not handled yet
        self.failures = {}              # account -> (digest, failed runs)
        # account -> (time of the last addition, mail ids); kept on disk.
        self.resort_path = state_path.with_name("resort.json")
        self.resort = self.load_resort()
        self.state = self.load_state()

    def load_state(self):
        try:
            return json.loads(self.state_path.read_text())
        except FileNotFoundError:
            return None
        except ValueError:
            say("state unreadable; starting over (current scripts recorded, no run)")
            return None

    def save_state(self):
        write_json(self.state_path, self.state)

    def load_resort(self):
        """Pending re-sorts left by the last run, due after the quiet time."""
        try:
            pending = json.loads(self.resort_path.read_text())
        except FileNotFoundError:
            return {}
        return {name: (self.clock(), set(ids)) for name, ids in pending.items()}

    def save_resort(self):
        """Under self.lock."""
        write_json(self.resort_path, {name: sorted(ids) for name, (_, ids) in self.resort.items()})

    def event(self):
        with self.lock:
            self.changed_at = self.clock()

    def waiting(self):
        with self.lock:
            return self.changed_at is not None

    def due(self):
        with self.lock:
            return self.changed_at is not None and self.clock() - self.changed_at >= QUIET_SECONDS

    def reconcile(self):
        """Compare every enabled account's active script with the one last
        applied; run resieve where they differ. Returns the accounts run."""
        with self.lock:
            self.changed_at = None
        first = self.state is None
        if first:
            self.state = {}
        ran = []
        for account in self.accounts():
            name = account["id"]
            try:
                digest = self.check(account)
            except Exception as error:      # Stalwart away: try again later
                say(f"{name}: cannot read the active script: {type(error).__name__}: {error}")
                continue
            if digest is None:
                self.state[name] = None
                continue
            if first or name not in self.state:
                self.state[name] = digest
                say(f"{name}: active script recorded{' (first start, no run)' if first else ''}")
                continue
            if self.state[name] == digest:
                continue
            failed_digest, failed = self.failures.get(name, (None, 0))
            if failed_digest == digest and failed >= MAX_FAILURES:
                continue
            say(f"{name}: active script changed; resieve --apply")
            try:
                ok = self.run(account)
            except Exception as exc:          # the watcher must keep running
                say(f"{name}: resieve could not start ({type(exc).__name__}: {exc})")
                ok = False
            if ok:
                self.state[name] = digest
                self.failures.pop(name, None)
                ran.append(name)
            else:
                failed = failed + 1 if failed_digest == digest else 1
                self.failures[name] = (digest, failed)
                if failed >= MAX_FAILURES:
                    say(f"{name}: run failed {failed} times; waiting for the next filter change")
                    try:
                        self.notify(account)
                        say(f"{name}: notice put into the INBOX")
                    except Exception as error:
                        say(f"{name}: notice failed: {type(error).__name__}: {error}")
                else:
                    say(f"{name}: run failed; tried again at the next check")
        self.save_state()
        return ran

    def add_resort(self, name, ids):
        """Mails a human moved into INBOX (or Junk): re-sorted together once
        the moves have gone quiet (a folder restructure moves many)."""
        with self.lock:
            _, pending = self.resort.get(name, (None, set()))
            self.resort[name] = (self.clock(), pending | set(ids))
            self.save_resort()

    def resort_due(self):
        """Run the re-sorts whose moves have been quiet long enough."""
        with self.lock:
            due = {n: ids for n, (at, ids) in self.resort.items() if self.clock() - at >= QUIET_SECONDS}
            for name in due:
                del self.resort[name]
            if due:
                self.save_resort()
        if not due:
            return []
        enabled = {a["id"]: a for a in self.accounts()}
        ran = []
        for name, ids in sorted(due.items()):
            if name not in enabled:
                say(f"{name}: re-sort not enabled (resieve.enabled false); {len(ids)} mail(s) left as they are")
                continue
            try:
                ok = self.run(enabled[name], resort_ids=ids)
            except Exception as exc:          # the watcher must keep running
                say(f"{name}: re-sort could not start ({type(exc).__name__}: {exc})")
                ok = False
            if ok:
                ran.append(name)
            else:
                say(f"{name}: re-sort failed; the mails stay where they are, handed back to the filter "
                    "(sorted at its next run)")
        return ran

    def loop(self, stopping):
        next_check = self.clock()
        while not stopping.is_set():
            # The hourly check waits for a pending change to go quiet too.
            if self.due() or (self.clock() >= next_check and not self.waiting()):
                self.reconcile()
                next_check = self.clock() + CHECK_SECONDS
            self.resort_due()
            stopping.wait(1)


class Hook(BaseHTTPRequestHandler):
    def do_POST(self):
        length = int(self.headers.get("Content-Length", "0"))
        try:
            body = json.loads(self.rfile.read(length))
        except ValueError:
            body = {}
        if self.path == "/resort":
            # From mail-provenance: a human moved mails into INBOX/Junk.
            name, ids = body.get("account"), body.get("email_ids")
            if isinstance(name, str) and isinstance(ids, list) and all(isinstance(i, str) for i in ids):
                try:
                    self.server.watcher.add_resort(name, ids)
                    self.send_response(200)
                except OSError as error:        # not kept: provenance asks again
                    say(f"{name}: re-sort not recorded ({error})")
                    self.send_response(500)
            else:
                self.send_response(400)
            self.end_headers()
            return
        events = body.get("events", []) if isinstance(body, dict) else []
        if any(str(e.get("type", "")).startswith("manage-sieve.") for e in events):
            self.server.watcher.event()
        self.send_response(200)
        self.end_headers()
        self.wfile.write(b"OK\n")

    def log_message(self, format, *args):
        return


def write_json(path, value):
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(value, indent=1, sort_keys=True) + "\n")
    tmp.replace(path)


def resieve_by_hand(args):
    """resieve-watch resieve ACCOUNT [--apply] [--limit N] [--mailbox PATH]:
    resieve for one account, with the account's own settings, output as it
    comes; exits with resieve's exit code."""
    usage = "usage: resieve-watch resieve ACCOUNT [--apply] [--limit N] [--mailbox PATH]"
    if not args or args[0].startswith("-"):
        sys.exit(usage)
    name, rest = args[0], list(args[1:])
    account = next((a for a in load_accounts(enabled_only=False) if a["id"] == name), None)
    if account is None:
        sys.exit(f"resieve: unknown account {name!r}")
    env = resieve_env(account, apply="--apply" in rest)
    rest = [a for a in rest if a != "--apply"]
    while rest:
        option = rest.pop(0)
        if option in ("--limit", "--mailbox") and rest:
            env["RESIEVE_LIMIT" if option == "--limit" else "RESIEVE_MAILBOX"] = rest.pop(0)
        else:
            sys.exit(f"resieve: unknown argument {option!r}\n{usage}")
    os.execve(RESIEVE, [RESIEVE], env)


def main():
    if sys.argv[1:2] == ["resieve"]:
        resieve_by_hand(sys.argv[2:])
    watcher = Watcher()
    server = ThreadingHTTPServer(("0.0.0.0", PORT), Hook)
    server.watcher = watcher
    threading.Thread(target=server.serve_forever, daemon=True).start()
    say(f"listening on :{PORT}; quiet {QUIET_SECONDS:.0f} s, check every {CHECK_SECONDS:.0f} s; "
        f"{len(load_accounts())} account(s) enabled")
    stopping = threading.Event()
    signal.signal(signal.SIGTERM, lambda *_: stopping.set())
    watcher.loop(stopping)
    server.shutdown()
    say("stopped")


if __name__ == "__main__":
    sys.exit(main())
